from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime

from app.assistant.capability import Capability
from app.assistant.execution import CapabilityExecutionRequest
from app.identity.models import UserRole


@dataclass(frozen=True)
class CapabilityConfirmation:
    """
    Durable authorization record for one exact prepared capability execution.

    A confirmation is bound to the authenticated session, user, business,
    and role that created it. It contains the exact trusted execution request
    that the user is being asked to approve.

    Confirmation records are single-use and time-limited. They are not AI
    instructions and must never be regenerated by re-processing the original
    user message.
    """

    confirmation_id: str
    session_id_hash: str
    user_id: str
    business_id: str
    role: UserRole
    request: CapabilityExecutionRequest
    created_at: datetime
    expires_at: datetime
    consumed_at: datetime | None = None
    revoked_at: datetime | None = None

    def __post_init__(self) -> None:
        for name, value in (
            ("confirmation_id", self.confirmation_id),
            ("session_id_hash", self.session_id_hash),
            ("user_id", self.user_id),
            ("business_id", self.business_id),
        ):
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"{name} must be a non-empty string.")

        if not isinstance(self.role, UserRole):
            raise TypeError("role must be a UserRole.")

        if not isinstance(
            self.request,
            CapabilityExecutionRequest,
        ):
            raise TypeError(
                "request must be a CapabilityExecutionRequest."
            )

        if self.request.business_id != self.business_id:
            raise ValueError(
                "Confirmation business_id must match the execution request."
            )

        for name, value in (
            ("created_at", self.created_at),
            ("expires_at", self.expires_at),
        ):
            if not isinstance(value, datetime):
                raise TypeError(f"{name} must be a datetime.")
            if value.tzinfo is None or value.utcoffset() is None:
                raise ValueError(
                    f"{name} must be timezone-aware."
                )

        if self.expires_at <= self.created_at:
            raise ValueError(
                "expires_at must be later than created_at."
            )

        for name, value in (
            ("consumed_at", self.consumed_at),
            ("revoked_at", self.revoked_at),
        ):
            if value is not None:
                if not isinstance(value, datetime):
                    raise TypeError(f"{name} must be a datetime or None.")
                if value.tzinfo is None or value.utcoffset() is None:
                    raise ValueError(
                        f"{name} must be timezone-aware when provided."
                    )

        if self.consumed_at is not None and self.revoked_at is not None:
            raise ValueError(
                "A confirmation cannot be both consumed and revoked."
            )

    @property
    def capability(self) -> Capability:
        return self.request.capability

    @property
    def operation(self) -> str:
        return self.request.operation

    def is_expired(self, now: datetime) -> bool:
        if not isinstance(now, datetime):
            raise TypeError("now must be a datetime.")
        if now.tzinfo is None or now.utcoffset() is None:
            raise ValueError("now must be timezone-aware.")
        return now >= self.expires_at

    def is_pending(self, now: datetime) -> bool:
        if not isinstance(now, datetime):
            raise TypeError("now must be a datetime.")
        if now.tzinfo is None or now.utcoffset() is None:
            raise ValueError("now must be timezone-aware.")

        return (
            self.consumed_at is None
            and self.revoked_at is None
            and now < self.expires_at
        )
